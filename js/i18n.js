/* ---------- language state ---------- */
const LANG_KEY = "substrata-lang";
const LANG = (() => {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === "ja" || saved === "en") return saved;
  return (navigator.language || "en").toLowerCase().startsWith("ja") ? "ja" : "en";
})();
document.documentElement.lang = LANG;

/* t("English") → Japanese when JA is on and a translation exists */
function t(en) {
  if (LANG !== "ja") return en;
  return Object.prototype.hasOwnProperty.call(JA, en) ? JA[en] : en;
}

/* pick a field from data.js: p.text / p.text_ja */
function tf(obj, field) {
  return LANG === "ja" && obj[field + "_ja"] ? obj[field + "_ja"] : obj[field];
}

function setLang(lang) {
  localStorage.setItem(LANG_KEY, lang);
  if (typeof transitionTo === "function") transitionTo(location.href);
  else location.reload();
}

/* translate static HTML marked with data-i18n / data-i18n-ph */
function applyI18n(root = document) {
  if (LANG !== "ja") return;
  const norm = s => s.replace(/\s+/g, " ").trim();
  root.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.dataset.i18n || norm(el.innerHTML);
    if (Object.prototype.hasOwnProperty.call(JA, key)) el.innerHTML = JA[key];
  });
  root.querySelectorAll("[data-i18n-ph]").forEach(el => {
    const key = el.getAttribute("placeholder");
    if (JA[key]) el.setAttribute("placeholder", JA[key]);
  });
  const title = norm(document.title);
  if (JA[title]) document.title = JA[title];
}
